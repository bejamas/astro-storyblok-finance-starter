import { renderRichText } from '@storyblok/astro'

// Renderers receive `children` as the already-rendered string of the node's content.
// Lists re-render each item individually so every item gets its own prefix
// (passing the full renderer map keeps nested lists in markdown too).
const renderListItems = ({ content = [] }, prefix) =>
	content
		.map((item, index) => `${prefix(index)}${renderRichText(item, { renderers: mdRenderers })}`)
		.join('')

// Display a generic fallback when the rich text field is empty
const paragraph = ({ children }) => {
	return children ? `\n${children}\n` : 'Provide content'
}

// Custom renderers for common types supported in the richtext package.
const mdRenderers = {
	blockquote: ({ children }) => `> ${children.replace('\n', '')}`,
	bold: ({ children }) => `**${children}**`,
	bullet_list: (node) => renderListItems(node, () => '- '),
	code: ({ children }) => `\`${children}\``,
	code_block: ({ children }) => `\n\`\`\`\n${children}\n\`\`\`\n`,
	heading: ({ attrs, children }) =>
		`\n${'#'.repeat(attrs.level)} ${children}\n`,
	image: ({ attrs }) =>
		`![${attrs.alt || 'Image description'}](${attrs.src})`,
	italic: ({ children }) => `*${children}*`,
	link: ({ attrs, children }) => `[${children}](${attrs?.href})`,
	list_item: ({ children }) => children.replace('\n', ''),
	ordered_list: (node) => renderListItems(node, (index) => `${index + 1}. `),
	paragraph: paragraph,
}

// Decode the sanitized HTML generated by the rich text package
export const convertedMarkdown = (richTextField) => {
	// Handle null/undefined input
	if (!richTextField) {
		return 'No content available'
	}

	try {
		const decodeHTML = renderRichText(richTextField, { renderers: mdRenderers })
		return String(decodeHTML)
			.replaceAll('&amp;', '&')
			.replaceAll('&lt;', '<')
			.replaceAll('&gt;', '>')
			.replaceAll('&quot;', '"')
			.replaceAll('&#039;', "'")
	} catch (error) {
		console.error('Error converting richtext to markdown:', error)
		return 'Content conversion failed'
	}
}
